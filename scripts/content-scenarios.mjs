// Placeholder substitution
export function fillPlaceholders(text, { brand = "бренд", product = "продукт", niche = "ниша" } = {}) {
  return text
    .replace(/\*{3,4}/g, product)
    .replace(/\(?\bваш(?:а|е|его|ей|ем|им)?\s+(?:продукт|товар|услуг[уаи]|проект|бренд|название|бизнес)\)?/gi, product)
    .replace(/\(?\bваш(?:а|е|его|ей|ем|им)?\s+(?:сфер[аеу]|ниш[аеу]|профессия|специальность)\)?/gi, niche)
    .replace(/\(?\bваш(?:а|е|его|ей|ем|им)?\s+(?:проект|блог|аккаунт|название\s+проекта)\)?/gi, brand)
    .replace(/\(название\)/gi, product)
    .replace(/название\s+продукта\/услуги/gi, product)
    .replace(/продукт\/услуга?/gi, product)
    .replace(/товар\/услуга?/gi, product);
}

// Detect poll/quiz elements in slide text; returns pollData object or null
function extractPollData(text) {
  // Explicit: (опрос: "question?" • opt1 • opt2)
  const explicitMatch = text.match(
    /\((?:опрос|голосование|викторина)[^:]*:\s*"?([^"•)\n]+)"?\s*((?:•\s*[^•)\n]+){1,4})\)/i
  );
  if (explicitMatch) {
    const question = explicitMatch[1].trim();
    const options = explicitMatch[2].split("•").map(o => o.trim()).filter(Boolean);
    const type = /викторина/i.test(text) ? "quiz" : "poll";
    return { type, question, options };
  }

  // Да/нет pattern — find nearest question
  if (/да\s+или\s+нет/i.test(text)) {
    const qMatch = text.match(/([^.\n]{8,60}\?)\s*(?:вот|да\s+или\s+нет)/i)
      || text.match(/вопрос\s*\d*[—:\.\s]+([^?\n]{5,60}\?)/i)
      || text.match(/([^.\n]{8,60}\?)/);
    const question = qMatch ? qMatch[1].trim() : "Правда или нет?";
    return { type: "poll", question, options: ["Да", "Нет"] };
  }

  // "выберите вариант" or "отметьте свой вариант"
  const choiceMatch = text.match(/([^.\n]{8,80}\?)\s*(?:выберите|отметьте|проголосуй)/i);
  if (choiceMatch) {
    return { type: "poll", question: choiceMatch[1].trim(), options: [] };
  }

  // Generic poll keywords with a question nearby
  if (/(?:проголосуй(?:те)?|голосование|устроим\s+перекличку|опросим\s+аудиторию)/i.test(text)) {
    const qMatch = text.match(/([^.\n]{8,80}\?)/);
    if (qMatch) return { type: "poll", question: qMatch[1].trim(), options: [] };
  }

  return null;
}

// Parse raw scenario text into slides by "Сторис N" markers
export function parseScenarioSlides(rawText, params = {}) {
  const filled = fillPlaceholders(rawText, params);

  // Split by "Сторис N" (with various endings: space, period, newline)
  const parts = filled.split(/\n?Сторис\s+\d+[.\s]/i).filter(p => p.trim());

  if (parts.length < 2) {
    // Fallback: split by double newlines
    const chunks = filled.split(/\n{2,}/).filter(p => p.trim().length > 20);
    return chunks.slice(0, 5).map((text, i) => {
      const pollData = extractPollData(text);
      return {
        text: cleanSlideText(text),
        label: `Слайд ${i + 1}`,
        ...(pollData && { type: pollData.type, pollData }),
      };
    });
  }

  return parts.slice(0, 6).map((text, i) => {
    const pollData = extractPollData(text);
    return {
      text: cleanSlideText(text),
      label: `Сторис ${i + 1}`,
      ...(pollData && { type: pollData.type, pollData }),
    };
  });
}

// Remove parenthetical UI instructions, keep the actual text
function cleanSlideText(text) {
  return text
    .replace(/\(наклейка[^)]*\)/gi, "")
    .replace(/\(опрос[^)]*\)/gi, "")
    .replace(/\(стрелк[^)]*\)/gi, "")
    .replace(/\(ползунок[^)]*\)/gi, "")
    .replace(/\(быстрая\s+реакция[^)]*\)/gi, "")
    .replace(/\(да\/нет\)/gi, "")
    .replace(/наклейка\s+"[^"]*"/gi, "")
    .replace(/наклейка\s+Вопросы?/gi, "")
    .replace(/наклейка\s+Опрос\b[^а-яА-Я]*/gi, "")
    .replace(/опрос\s+"[^"]*"/gi, "")
    .replace(/стрелка\s+вниз[^а-яА-Я]*/gi, "")
    .replace(/\n{2,}/g, " ")
    .replace(/\s{2,}/g, " ")
    .trim()
    .slice(0, 350);
}

