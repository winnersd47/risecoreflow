export function listScenarios() {
  const lines = [];
  for (const [key, cat] of Object.entries(SCENARIOS)) {
    lines.push(`\n${cat.label} (${cat.shortcodes.join(" | ")})`);
    cat.items.forEach((item, i) =>
      lines.push(`  ${String(i + 1).padStart(2, "0")}. ${item.name}`)
    );
  }
  return lines.join("\n");
}

export function findScenario(typeArg, numArg) {
  const num = parseInt(numArg, 10);
  if (isNaN(num) || num < 1) return null;

  for (const [, cat] of Object.entries(SCENARIOS)) {
    if (cat.shortcodes.some(s => s.toLowerCase() === typeArg.toLowerCase())) {
      const item = cat.items[num - 1];
      if (!item) return null;
      return { cat, item };
    }
  }
  return null;
}
